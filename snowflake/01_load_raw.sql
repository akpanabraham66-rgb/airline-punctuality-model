USE ROLE ACCOUNTADMIN;
USE WAREHOUSE PUNCTUALITY_WH;
USE SCHEMA PUNCTUALITY.RAW;

CREATE FILE FORMAT IF NOT EXISTS BTS_CSV
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS BTS_STAGE
    FILE_FORMAT = BTS_CSV;

CREATE TABLE IF NOT EXISTS FLIGHTS (
    FL_DATE             VARCHAR,
    OP_UNIQUE_CARRIER   VARCHAR,
    TAIL_NUM            VARCHAR,
    OP_CARRIER_FL_NUM   VARCHAR,
    ORIGIN              VARCHAR,
    DEST                VARCHAR,
    CRS_DEP_TIME        VARCHAR,
    DEP_DELAY           VARCHAR,
    ARR_DELAY           VARCHAR,
    CANCELLED           VARCHAR,
    CANCELLATION_CODE   VARCHAR,
    DIVERTED            VARCHAR,
    CARRIER_DELAY       VARCHAR,
    WEATHER_DELAY       VARCHAR,
    NAS_DELAY           VARCHAR,
    SECURITY_DELAY      VARCHAR,
    LATE_AIRCRAFT_DELAY VARCHAR
);
LIST @BTS_STAGE;

COPY INTO FLIGHTS
    FROM @BTS_STAGE
    ON_ERROR = 'ABORT_STATEMENT';

-- Criterion 1: total flights
SELECT COUNT(*) AS FLIGHTS
FROM FLIGHTS;

-- Flights per month, to compare with each file
SELECT SPLIT_PART(FL_DATE, '/', 1) AS month, COUNT(*) AS FLIGHTS
FROM FLIGHTS
GROUP BY month
ORDER BY month;

-- Criterion 3: empty values (plus tail number, for the first wave)
SELECT
    COUNT_IF(FL_DATE IS NULL)                AS no_date,
    COUNT_IF(OP_UNIQUE_CARRIER IS NULL)      AS no_AIRLINE,
    COUNT_IF(ORIGIN IS NULL)                 AS no_ORIGIN,
    COUNT_IF(DEST IS NULL)                   AS no_dest,
    COUNT_IF(TAIL_NUM IS NULL)               AS no_tail
FROM FLIGHTS;

--Date range, and does every date convert?
SELECT
    MIN(TRY_TO_DATE(SPLIT_PART(FL_DATE, ' ', 1), 'MM/DD/YYYY')) AS first_day,
    MAX(TRY_TO_DATE(SPLIT_PART(FL_DATE, ' ', 1), 'MM/DD/YYYY')) AS last_day,
    COUNT_IF(TRY_TO_DATE(SPLIT_PART(FL_DATE, ' ', 1), 'MM/DD/YYYY') IS NULL) AS bad_dates
FROM FLIGHTS;

SELECT CANCELLED, COUNT(*) AS FLIGHTS
FROM FLIGHTS
WHERE TAIL_NUM IS NULL
GROUP BY CANCELLED;
